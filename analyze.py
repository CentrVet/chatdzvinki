def analyze(transcript: str) -> dict:
    client = Anthropic(api_key=config.ANTHROPIC_API_KEY)
    msg = client.messages.create(
        model="claude-haiku-4-5",
        max_tokens=1500,
        messages=[{"role": "user", "content": _build_prompt(transcript)}],
    )
    data = _parse_json(_extract_text(msg))
    if data.get("is_supplier"):
        return {"is_supplier": True, "reason": data.get("reason", "")}

    # нормализация
    scores = data.get("scores", {}) or {}
    for key, _ in CRITERIA:
        scores[key] = max(0, min(2, int(scores.get(key, 0))))
    data["scores"] = scores
    data["total_score"] = sum(scores.values())
    data["max_score"] = len(CRITERIA) * 2
    data["risk"] = max(0, min(3, int(data.get("risk", 0))))
    data["language"] = data.get("language", "uk")
    # booked: True/False/None
    b = data.get("booked")
    data["booked"] = None if b is None else bool(b)
    # missed_upsell: str or None
    mu = data.get("missed_upsell")
    data["missed_upsell"] = mu if (isinstance(mu, str) and mu.strip()) else None
    # source: str or None
    src = data.get("source")
    data["source"] = src.strip().lower() if (isinstance(src, str) and src.strip()) else None
    for k in ("summary", "reason", "fix"):
        data.setdefault(k, "")
    return data
