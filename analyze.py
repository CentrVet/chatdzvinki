def _extract_text(msg) -> str:
    for b in msg.content:
        if getattr(b, "type", None) == "text":
            return b.text.strip()
    return ""


def _parse_json(text: str) -> dict:
    if text.startswith("```"):
        text = text.split("```")[1]
        if text.startswith("json"):
            text = text[4:]
        text = text.strip()
    return json.loads(text)


